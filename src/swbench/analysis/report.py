"""Write RESULTS.md from a directory of runs.

The report is regenerated from data every time; there is no hand-written
results prose to drift out of sync with the numbers.
"""

from __future__ import annotations

import math
from pathlib import Path

import pandas as pd

from swbench.analysis.aggregate import (
    compute_bound_warnings,
    cost_table,
    label_efficiency,
    load_results,
    summarize,
    verdicts,
)
from swbench.analysis.plots import cost_accuracy_plot, label_efficiency_plot


def _fmt(v, digits: int = 3) -> str:
    if v is None or (isinstance(v, float) and math.isnan(v)):
        return "–"
    if isinstance(v, float):
        if math.isinf(v):
            return "> tested range" if v > 0 else "< tested range"
        return f"{v:.{digits}f}"
    return str(v)


INT_COLUMNS = {"label_budget", "params_total", "params_trainable", "n_seeds", "n_pairs"}


def _md_table(df: pd.DataFrame, digits: int = 3) -> str:
    cols = list(df.columns)
    lines = ["| " + " | ".join(cols) + " |", "|" + "|".join("---" for _ in cols) + "|"]
    for r in df.to_dict("records"):
        cells = []
        for c in cols:
            v = r[c]
            if c in INT_COLUMNS and isinstance(v, float) and v.is_integer():
                v = int(v)
            cells.append(_fmt(v, digits))
        lines.append("| " + " | ".join(cells) + " |")
    return "\n".join(lines)


def _pivot(df: pd.DataFrame, split: str) -> pd.DataFrame:
    s = summarize(df, split)
    s["cell"] = [
        f"{m:.3f} ± {sd:.3f}" if n > 1 and not math.isnan(sd) else f"{m:.3f}"
        for m, sd, n in zip(s["mean"], s["std"], s["n_seeds"], strict=True)
    ]
    p = s.pivot(index="arm", columns="label_budget", values="cell").reset_index()
    p.columns = ["arm"] + [f"N={c}" for c in p.columns[1:]]
    return p


def write_report(
    runs_dir: str | Path,
    out_dir: str | Path,
    baseline: str = "unet13",
    profiles_csv: str | Path | None = None,
    min_gain: float = 0.02,
) -> Path:
    df = load_results(runs_dir)
    out_dir = Path(out_dir)
    fig_dir = out_dir / "figures"
    fig_dir.mkdir(parents=True, exist_ok=True)
    df.to_csv(out_dir / "all_runs.csv", index=False)

    splits = [s for s in ("test", "bolivia") if f"{s}_iou_water" in df]
    label_efficiency_plot(df, fig_dir / "label_efficiency", splits=tuple(splits))
    for n in sorted(df.label_budget.unique())[:1] + sorted(df.label_budget.unique())[-1:]:
        cost_accuracy_plot(df, fig_dir / f"cost_vs_accuracy_N{n}", split=splits[0], budget=int(n))

    profiles = pd.read_csv(profiles_csv) if profiles_csv and Path(profiles_csv).exists() else None
    cost = cost_table(df, profiles)
    train_pflops = (
        dict(zip(cost.arm, cost.train_pflops_per_run, strict=True)) if "train_pflops_per_run" in cost else None
    )
    md = ["# Results", ""]
    md.append(
        f"Generated by `swbench-report` from {len(df)} runs "
        f"({df.arm.nunique()} arms × {df.label_budget.nunique()} label budgets × "
        f"up to {df.groupby(['arm', 'label_budget']).seed.nunique().max()} seeds). "
        f"Device(s): {', '.join(sorted(df.device.astype(str).unique()))}."
    )
    md += ["", "![Label efficiency](figures/label_efficiency.png)", ""]

    for split in splits:
        md += [f"## Water IoU – {split}", "", "Mean ± std over seeds.", "", _md_table(_pivot(df, split)), ""]

    arms = [a for a in sorted(df.arm.unique()) if a != baseline]
    if baseline in set(df.arm):
        for split in splits:
            md += [f"## Label efficiency vs. `{baseline}` – {split}", ""]
            md.append(
                "`label_multiplier` = labelled chips the baseline needs to match the arm, divided by the "
                "chips the arm used (log-linear interpolation of the baseline's mean curve). "
                "`< tested range`: the baseline already does better with its smallest budget."
            )
            md.append("")
            for arm in arms:
                le = label_efficiency(df, arm, baseline, split)
                md += [f"**{arm}**", "", _md_table(le, 2), ""]

        md += ["## Is the foundation model worth it?", ""]
        md.append(
            f"Matched-seed IoU gain over `{baseline}` with a bootstrap 95% CI over seeds. "
            f"`justified` = whole CI above +{min_gain:.2f} IoU; `not justified` = whole CI below it; "
            "otherwise `inconclusive`. Extra cost is relative to the baseline: measured training seconds "
            "(on the device listed above) and, when profiles are available, training PFLOPs, which the "
            "per-IoU-point rate uses. The rate is `–` when there is no gain or no extra cost."
        )
        md.append("")
        for split in splits:
            for arm in arms:
                v = verdicts(df, arm, baseline, split, min_gain=min_gain, train_pflops=train_pflops)
                if not v.empty:
                    md += [f"**{arm} – {split}**", "", _md_table(v, 3), ""]

    md += ["## Cost accounting", "", _md_table(cost, 3), ""]
    warnings = compute_bound_warnings(cost)
    if warnings:
        md += [
            "**Training time is not compute-bound for every arm.** "
            + "; ".join(warnings)
            + ". For these arms wall-clock seconds (and GPU energy, which includes idle power) reflect data "
            "loading and node load as much as the model, so compare training cost by FLOPs, and inference "
            "cost by the profiled throughput (`infer_km2_per_s`), which is measured without data loading.",
            "",
        ]
    md += [
        f"![Cost vs accuracy](figures/cost_vs_accuracy_N{int(sorted(df.label_budget.unique())[0])}.png)",
        "",
        "See docs/COST_ACCOUNTING.md for how each column is measured.",
    ]
    path = out_dir / "RESULTS.md"
    path.write_text("\n".join(md) + "\n")
    return path
